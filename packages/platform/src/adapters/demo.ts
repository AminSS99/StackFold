import type {
  CacheIsolationPlatformPayload,
  CacheIsolationPlatformRequest,
  PreferredEditor,
  QueueCompatibilityPlatformPayload,
  QueueCompatibilityPlatformRequest,
  ScanPlatformParams,
  ScanPlatformResult,
  SignatureCompatibilityPlatformPayload,
  SignatureCompatibilityPlatformRequest,
} from '../types';
import type { PathValidationResult, ScanProgress, StackfoldScanArtifact } from '@stackfold/scanner';
import { WebPlatformAdapter } from './web';

export interface StaticDemoOptions {
  /** URL prefix the static site is served under, e.g. `/StackFold` on GitHub Pages. */
  basePath?: string;
  /** Repository used for "open in editor" deep links. */
  repositoryUrl?: string;
  branch?: string;
}

const DEMO_ROOT_PREFIX = '/demo/';
const SELF_FIXTURE = 'stackfold-self';

/**
 * Serves pre-computed results (generated by `apps/web/scripts/build-demo-data.mjs`
 * with the real scanner) so the app can be hosted as a static site with no server
 * and no access to anyone's filesystem. Everything not backed by demo data fails
 * with an explicit, honest message instead of pretending to work.
 */
export class StaticDemoPlatformAdapter extends WebPlatformAdapter {
  private readonly base: string;
  private readonly repositoryUrl: string;
  private readonly branch: string;

  constructor(options: StaticDemoOptions = {}) {
    super();
    this.base = (options.basePath ?? '').replace(/\/+$/, '');
    this.repositoryUrl = (options.repositoryUrl ?? 'https://github.com/AminSS99/StackFold').replace(/\/+$/, '');
    this.branch = options.branch ?? 'main';
  }

  private url(rel: string): string {
    return `${this.base}/demo-data/${rel}`;
  }

  private fixtureFrom(params: { fixture?: string; rootPath?: string }): string | undefined {
    if (params.fixture) return params.fixture;
    if (params.rootPath?.startsWith(DEMO_ROOT_PREFIX)) {
      return params.rootPath.slice(DEMO_ROOT_PREFIX.length).split('/')[0];
    }
    return undefined;
  }

  private async getJson<T>(rel: string, signal?: AbortSignal): Promise<{ ok: boolean; status: number; data: T | null }> {
    try {
      const res = await fetch(this.url(rel), { signal });
      if (!res.ok) return { ok: false, status: res.status, data: null };
      return { ok: true, status: res.status, data: (await res.json()) as T };
    } catch (err) {
      if (err instanceof Error && err.name === 'AbortError') throw err;
      return { ok: false, status: 0, data: null };
    }
  }

  async validateRepository(targetPath: string): Promise<PathValidationResult> {
    const fixture = this.fixtureFrom({ rootPath: targetPath });
    if (fixture) {
      return {
        isValid: true,
        canonicalPath: targetPath,
        projectName: fixture,
        hasPackageJson: true,
        hasTsConfig: true,
        hasPrisma: false,
        isMonorepo: false,
      };
    }
    return {
      isValid: false,
      hasPackageJson: false,
      hasTsConfig: false,
      hasPrisma: false,
      isMonorepo: false,
      errorCode: 'DEMO_STATIC',
      errorMessage: 'This hosted demo only includes pre-scanned projects. Install Stackfold or run the CLI to scan your own repository.',
    };
  }

  async scanRepository(
    params: ScanPlatformParams,
    onProgress?: (progress: ScanProgress) => void,
    signal?: AbortSignal
  ): Promise<ScanPlatformResult> {
    const fixture = this.fixtureFrom(params);
    if (!fixture) {
      throw new Error(
        'This hosted demo only includes pre-scanned projects. Install Stackfold or run the CLI to scan your own repository.'
      );
    }
    onProgress?.({ stage: 'VALIDATING_PATH', message: 'Loading pre-scanned project…' });
    const { ok, data } = await this.getJson<{
      graph: ScanPlatformResult['graph'];
      durationMs: number;
      scannedFilesCount: number;
      diagnostics?: ScanPlatformResult['diagnostics'];
      canonicalPath?: string;
    }>(`scan/${fixture}.json`, signal);
    if (!ok || !data) throw new Error(`No pre-scanned demo data for '${fixture}'.`);
    onProgress?.({ stage: 'COMPLETED', message: 'Scan complete' });
    return {
      graph: data.graph,
      durationMs: data.durationMs,
      scannedFilesCount: data.scannedFilesCount,
      diagnostics: data.diagnostics ?? [],
      fromCache: false,
      canonicalPath: data.canonicalPath,
    };
  }

  async loadCachedScan(_rootPath: string): Promise<StackfoldScanArtifact | null> {
    return null;
  }

  async deleteCachedScan(_rootPath: string): Promise<boolean> {
    return false;
  }

  async openInEditor(
    filePath: string,
    rootPath: string,
    _editor: PreferredEditor = 'vscode'
  ): Promise<{ success: boolean; url?: string; error?: string }> {
    const fixture = this.fixtureFrom({ rootPath });
    const clean = filePath.replace(/^\/+/, '');
    const inRepo = !fixture || fixture === SELF_FIXTURE ? clean : `fixtures/${fixture}/${clean}`;
    const url = `${this.repositoryUrl}/blob/${this.branch}/${inRepo}`;
    await this.openExternalUrl(url);
    return { success: true, url };
  }

  private async securityPayload<T extends { success: boolean }>(
    kind: 'queue-compatibility' | 'signature-compatibility' | 'cache-isolation',
    request: { fixture?: string; rootPath?: string },
    fallbackFixture: string
  ): Promise<T> {
    const fixture = this.fixtureFrom(request) ?? fallbackFixture;
    const { ok, data } = await this.getJson<T>(`security/${kind}/${fixture}.json`);
    if (ok && data) return data;
    return {
      success: false,
      error: `No Security Lab configuration is bundled in this demo for '${fixture}'.`,
      code: 'MISSING_CONFIGURATION',
      source: `fixture:${fixture}`,
    } as unknown as T;
  }

  loadQueueCompatibilityRecorded(request: QueueCompatibilityPlatformRequest): Promise<QueueCompatibilityPlatformPayload> {
    return this.securityPayload('queue-compatibility', request, 'queue-compatibility-failing');
  }

  runQueueCompatibilityCheck(request: QueueCompatibilityPlatformRequest): Promise<QueueCompatibilityPlatformPayload> {
    return this.securityPayload('queue-compatibility', request, 'queue-compatibility-failing');
  }

  loadSignatureCompatibilityRecorded(request: SignatureCompatibilityPlatformRequest): Promise<SignatureCompatibilityPlatformPayload> {
    return this.securityPayload('signature-compatibility', request, 'signature-compatibility-vulnerable');
  }

  runSignatureCompatibilityProbe(request: SignatureCompatibilityPlatformRequest): Promise<SignatureCompatibilityPlatformPayload> {
    return this.securityPayload('signature-compatibility', request, 'signature-compatibility-vulnerable');
  }

  loadCacheIsolationRecorded(request: CacheIsolationPlatformRequest): Promise<CacheIsolationPlatformPayload> {
    return this.securityPayload('cache-isolation', request, 'cache-isolation-vulnerable');
  }

  async runCacheIsolationProbe(request: CacheIsolationPlatformRequest): Promise<CacheIsolationPlatformPayload> {
    const recorded = await this.loadCacheIsolationRecorded(request);
    if (recorded.success) return recorded;
    return {
      ...recorded,
      error: 'Live Cache Isolation probes drive two Chromium sessions and need the desktop app or CLI. The recorded result is shown instead.',
      code: 'DEMO_STATIC',
    };
  }
}
